'use client';

import type { TotpSetupResponse } from '@eta/shared';
import { useTranslations } from 'next-intl';
import { useEffect, useRef, useState } from 'react';
import { FormAlert } from '@/components/forms/FormAlert';
import { ApiError } from '@/lib/api/api-error';
import { apiRequest } from '@/lib/api/client';
import { TotpCodeForm } from './TotpCodeForm';

/** Shows the QR code (and the key for manual entry), then asks for the first code. */
export function TotpSetup() {
  const t = useTranslations();
  const [setup, setSetup] = useState<TotpSetupResponse | null>(null);
  const [errorCode, setErrorCode] = useState<string | null>(null);
  // Each call creates a new secret, so it must run exactly once (React may run effects twice in development).
  const requested = useRef(false);

  useEffect(() => {
    if (requested.current) return;
    requested.current = true;
    apiRequest<TotpSetupResponse>('POST', '/api/auth/2fa/setup')
      .then(setSetup)
      .catch((error: unknown) => {
        setErrorCode(error instanceof ApiError ? error.code : 'generic');
      });
  }, []);

  if (errorCode) {
    return (
      <FormAlert tone="error">
        {t.has(`errors.${errorCode}`) ? t(`errors.${errorCode}`) : t('errors.generic')}
      </FormAlert>
    );
  }
  if (!setup) return <p role="status">{t('TwoFactor.loadingQr')}</p>;

  const manualKey = new URL(setup.otpauthUrl).searchParams.get('secret') ?? '';
  return (
    <div className="flex flex-col gap-6">
      {/* eslint-disable-next-line @next/next/no-img-element -- data URL generated by the API */}
      <img
        src={setup.qrCodeDataUrl}
        alt={t('TwoFactor.qrAlt')}
        width={240}
        height={240}
        className="self-center"
      />
      <div className="text-sm">
        <p className="text-ink-muted">{t('TwoFactor.manualKey')}</p>
        <code
          dir="ltr"
          className="mt-1 block break-all rounded bg-sand px-3 py-2 font-mono text-ink"
        >
          {manualKey}
        </code>
      </div>
      <TotpCodeForm endpoint="/api/auth/2fa/enable" />
    </div>
  );
}
